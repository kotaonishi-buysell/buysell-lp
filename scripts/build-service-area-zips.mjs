// Builds src/content/service-area-zips.ts: the ZIP codes of the counties we visit.
//
//   node scripts/build-service-area-zips.mjs <path to GeoNames US.txt>
//
// Source: GeoNames postal codes for the US (Creative Commons Attribution 4.0, https://www.geonames.org),
// as bundled in the npm package zipcodes-us@1.2.0 (data/US.txt). Get it into an empty folder with
// `npm pack zipcodes-us@1.2.0`, unpack it, and pass the path of data/US.txt.
// The counties are the ones of the two US Census Bureau metropolitan areas (OMB 2023 delineation):
// Dallas-Fort Worth-Arlington and Houston-Pasadena-The Woodlands. To change the area, edit COUNTIES
// below and run this again. Check the result against current USPS or HUD data before relying on it.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const COUNTIES = {
  'Dallas–Fort Worth': ['Collin', 'Dallas', 'Denton', 'Ellis', 'Hunt', 'Johnson', 'Kaufman', 'Parker', 'Rockwall', 'Tarrant', 'Wise'],
  Houston: ['Austin', 'Brazoria', 'Chambers', 'Fort Bend', 'Galveston', 'Harris', 'Liberty', 'Montgomery', 'Waller'],
};

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/build-service-area-zips.mjs <path to GeoNames US.txt>');
  process.exit(1);
}

// Columns of US.txt: country, ZIP, place, state, state code, county, county code, ..., lat, lon, accuracy
const rows = readFileSync(source, 'utf8')
  .split('\n')
  .map((line) => line.split('\t'))
  .filter((r) => r.length >= 7 && r[4] === 'TX');

const countiesInData = new Set(rows.map((r) => r[5]));
const zipsByArea = {};
for (const [area, counties] of Object.entries(COUNTIES)) {
  for (const county of counties) {
    if (!countiesInData.has(county)) throw new Error(`County not found in the data: ${county}`);
  }
  zipsByArea[area] = [...new Set(rows.filter((r) => counties.includes(r[5])).map((r) => r[1]))].sort();
}
const all = [...new Set(Object.values(zipsByArea).flat())].sort();
for (const zip of all) if (!/^\d{5}$/.test(zip)) throw new Error(`Not a 5-digit ZIP code: ${zip}`);

const format = (zips) => {
  const lines = [];
  for (let i = 0; i < zips.length; i += 10) lines.push('  ' + zips.slice(i, i + 10).map((z) => `'${z}'`).join(', ') + ',');
  return lines.join('\n');
};

const output = `/*
 * GENERATED by scripts/build-service-area-zips.mjs. Do not edit by hand; change the script and run it again.
 *
 * The ZIP codes we visit: every ZIP code in the counties of the Dallas–Fort Worth and the Houston
 * metropolitan areas (US Census Bureau, OMB 2023 delineation). ${all.length} ZIP codes.
 * Source: GeoNames postal codes (Creative Commons Attribution 4.0, https://www.geonames.org),
 * via the npm package zipcodes-us@1.2.0. Check against current USPS or HUD data before relying on it.
 */

/** The counties of each area. */
export const serviceAreaCounties = ${JSON.stringify(COUNTIES, null, 2)} as const;

${Object.entries(zipsByArea).map(([area, zips]) => `/** ${area}: ${zips.length} ZIP codes. */\nexport const ${area.startsWith('Dallas') ? 'dallasFortWorthZips' : 'houstonZips'}: string[] = [\n${format(zips)}\n];`).join('\n\n')}

/** Every ZIP code we visit, sorted. */
export const serviceAreaZips: string[] = [...new Set([...dallasFortWorthZips, ...houstonZips])].sort();
`;
writeFileSync(resolve(dirname(fileURLToPath(import.meta.url)), '../src/content/service-area-zips.ts'), output);
console.log(`Wrote src/content/service-area-zips.ts: ${Object.entries(zipsByArea).map(([a, z]) => `${a} ${z.length}`).join(', ')}, total ${all.length}.`);
